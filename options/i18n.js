// Locale used to format dates and times.
const DATE_LOCALE = { en: "en-GB", fr: "fr-FR", zh: "zh-CN" };

const LANGUAGES = ["en", "zh", "fr"]; // order of the switch: EN · 中文 · FR
let currentLang = "en";

function t(key, values = {}) {
  const text = I18N[currentLang]?.[key] ?? I18N.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (match, name) => (name in values ? String(values[name]) : match));
}

// Picks "<key>.one" or "<key>.other" from the count `n`.
const tn = (key, n, values = {}) => t(`${key}.${n === 1 ? "one" : "other"}`, { n, ...values });

// The browser's language, if we have it; English otherwise.
function defaultLanguage() {
  const ui = browser.i18n.getUILanguage().toLowerCase();
  if (ui.startsWith("fr")) return "fr";
  if (ui.startsWith("zh")) return "zh";
  return "en";
}

// Applies the current language to every static text of the page.
function translateStatic() {
  document.documentElement.lang = currentLang === "zh" ? "zh-CN" : currentLang;
  document.title = t("pageTitle");
  for (const element of document.querySelectorAll("[data-i18n]")) element.textContent = t(element.dataset.i18n);
  for (const element of document.querySelectorAll("[data-i18n-aria]")) {
    element.setAttribute("aria-label", t(element.dataset.i18nAria));
  }
}
